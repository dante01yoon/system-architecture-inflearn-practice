"""면접 문제의 읽기·쓰기 모양을 받아 DB 종류를 이유와 함께 고른다."""
RULES = [  # (조건 이름, DB 종류, 이유)
    ("key", "키-값", "키 하나로 값 하나를 읽는다"),
    ("join", "관계형", "관계가 많고 트랜잭션이 필요하다"),
    ("hops", "그래프", "친구의 친구처럼 여러 번 건너간다"),
    ("append", "와이드 컬럼", "쓰기가 아주 많고 키 안에서 시간순으로 읽는다"),
    ("text", "검색 인덱스", "단어로 찾고 점수로 줄 세운다"),
    ("metric", "시계열", "시각마다 숫자를 쌓고 구간으로 묶는다"),
]


def suggest(needs):
    """needs = 이 문제에 맞는 조건 이름들. 맞는 규칙을 순서대로 돌려준다."""
    picks = [(kind, why) for name, kind, why in RULES if name in needs]
    return picks or [("관계형", "특별한 이유가 없으면 기본값")]


