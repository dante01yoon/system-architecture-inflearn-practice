"""서점 유틸리티 트리(품질 → 세부 → 시나리오)와 설계 결정. ATAM(CMU/SEI-2000-TR-004)의 말을 그대로 쓴다."""
RANK = {"H": 3, "M": 2, "L": 1}

# (품질, 세부, 시나리오 id, 시나리오, 중요도, 어려움)
TREE = [
    ("성능", "반짝 할인 처리량", "P1", "할인 때 주문 열 배 → 99%가 2초 안에 접수", "H", "H"),
    ("성능", "검색 응답", "P2", "책 검색 결과가 0.5초 안에", "M", "L"),
    ("가용성", "결제 대행사 장애", "A1", "결제 무응답 → 결제 대기로 접수, 유실 0건", "H", "H"),
    ("가용성", "서버 고장", "A2", "주문 서버 한 대가 멈춰도 30초 안에 복구", "M", "M"),
    ("변경 용이성", "쿠폰 규칙", "M1", "새 쿠폰 종류를 주문 코드 수정 없이 3일 안에", "H", "M"),
]

# 설계 결정 → 품질마다 +1(좋아짐) / -1(나빠짐)
DECISIONS = {
    "주문을 큐로 받기": {"성능": +1, "가용성": +1},
    "결제에 서킷 브레이커": {"가용성": +1},
    "쿠폰 규칙을 플러그인으로": {"변경 용이성": +1, "성능": -1},
    "결제 재시도 다섯 번": {"가용성": +1, "성능": -1},
}


def ranked(tree):
    """(중요도, 어려움)이 높은 시나리오부터. 같으면 트리 순서."""
    return sorted(tree, key=lambda s: (-RANK[s[4]], -RANK[s[5]]))


def classify(effects):
    """품질 둘 이상을 서로 반대로 움직이면 트레이드오프 지점, 아니면 민감 지점."""
    return "트레이드오프" if len(set(effects.values())) > 1 else "민감 지점"


def risks(tree, decisions):
    """(H,H) 시나리오의 품질을 깎는 결정 = 위험 후보. [(결정, 시나리오 id, 품질)]"""
    hh = [(s[2], s[0]) for s in tree if s[4] == s[5] == "H"]
    return [(d, sid, q) for d, eff in decisions.items() for sid, q in hh if eff.get(q, 0) < 0]
